# При повороте сильнее этого угла глаза считаются невидимыми
EYES_HIDDEN_YAW_DEG = 60.0

# Норма открытых глаз в зависимости от наклона головы. Когда голова откинута
# назад или опущена, глаза на камере выглядят уже — EAR падает при открытых
# глазах. Норма EAR запоминается отдельно для каждого диапазона наклона.
POSE_EYE_NORM = True
# В диапазоне калибровки (±POSE_BIN_DEG/2) всегда используется калиброванная норма.

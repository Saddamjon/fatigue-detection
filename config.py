# --- Кивок: медленное падение головы и резкий возврат -----------------------
# Откинутая или наклонённая голова без движения — это поза, а не кивок.
# Сонный кивок: голова медленно уходит от нормы, затем резко возвращается.
NOD_DROP_DEG = 12.0           # минимальное отклонение от нормы

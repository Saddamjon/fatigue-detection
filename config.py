FALLBACK_CLOSED_EAR_RATIO = 0.3
FALLBACK_CLOSED_BLINK = 0.8   # «закрытый» уровень blendshape по умолчанию
# Медианный фильтр признаков глаз (подавляет дрожание точек). Включается
# только при частоте кадров не ниже MEDIAN_MIN_FPS: при низкой частоте
# моргание длится 1–2 кадра, и фильтр стёр бы его.
MEDIAN_FRAMES = 3
MEDIAN_MIN_FPS = 20

# --- Прищур ---------------------------------------------------------------
# Прищур: оценка eyeSquint выше личной нормы на SQUINT_DELTA, а нейросеть
# не видит закрытия. Тогда EAR ненадёжен и используется только нейросеть.
SQUINT_DELTA = 0.20

# --- Ракурс головы -----------------------------------------------------------
# При повороте головы сильнее этого угла EAR искажается — используется только
# оценка нейросети (в режиме "ear" такие кадры не учитываются)

# --- Поза водителя: подстройка нормы ----------------------------------------
# Водитель может сидеть откинувшись, облокотившись, с наклонённой головой.
# Если новая поза держится POSE_ADAPT_SEC секунд при открытых глазах,
# она становится новой нормой (это смена позы, а не кивок).

# --- Определение закрытых глаз -------------------------------------------
# Открытость глаза 0..1 считается внутри ЛИЧНОГО диапазона:
#   0 — уровень закрытых глаз, 1 — уровень открытых глаз (из калибровки).
# Глаз считается закрытым, если открытость ниже CLOSED_LEVEL.
CLOSED_LEVEL = 0.5
# Какой признак используется: "ear" — геометрия точек, "blendshape" — оценка
# моргания от нейросети, "fused" — среднее двух (по умолчанию).
# Адаптация к прищуру и повороту головы работает только в режиме "fused".
EYE_MODE = "fused"
FUSION_WEIGHT_EAR = 0.5       # вес EAR при объединении (остальное — blendshape)
# Если этап закрытых глаз не удался: «закрытый» EAR = доля открытого.

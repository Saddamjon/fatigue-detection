POSE_BIN_MIN_SAMPLES = 30     # сколько кадров нужно, чтобы доверять норме диапазона
POSE_BIN_MAXLEN = 300         # после стольких кадров норма диапазона замораживается
# Норма диапазона может отличаться от калиброванной только в этих пределах —
# иначе система «привыкла» бы к постепенно закрывающимся глазам
POSE_NORM_MIN_RATIO = 0.70
POSE_NORM_MAX_RATIO = 1.15
# Кадр используется для обучения нормы, только если нейросеть уверенно видит

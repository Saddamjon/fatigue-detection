NOD_PEAK_SHARE = 0.85         # «нижняя точка» — отклонение не меньше 85% максимума
NOD_MAX_RECOVERY_SEC = 0.8    # возврат не медленнее этого
NOD_RETURN_SHARE = 0.4        # возврат засчитан, когда отклонение < 40% максимума
# Прежнее правило (используется с --no-adapt, для сравнения в экспериментах):
